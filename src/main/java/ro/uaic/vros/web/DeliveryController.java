package ro.uaic.vros.web;

import java.net.URI;
import java.time.Instant;
import java.util.List;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import ro.uaic.vros.model.Delivery;
import ro.uaic.vros.service.DeliveryService;

/**
 * LAB 5 HOMEWORK 2 + 3: Delivery CRUD.
 * A delivery belongs to an existing customer (customerId in the DTO).
 * Registration time is generated by the server and is not client-editable.
 */
@RestController
@RequestMapping("/api/deliveries")
public class DeliveryController {
    private final DeliveryService service;

    public DeliveryController(DeliveryService service) { this.service = service; }

    public record DeliveryRequest(
            @NotNull @Positive Long customerId,
            @Positive int quantity,
            @Size(max = 1000) String notes) {}

    public record DeliveryResponse(Long id, Long customerId, int quantity,
                                   String notes, Instant registeredAt) {
        public static DeliveryResponse from(Delivery delivery) {
            return new DeliveryResponse(delivery.getId(), delivery.getCustomer().getId(),
                    delivery.getQuantity(), delivery.getNotes(), delivery.getRegisteredAt());
        }
    }

    @GetMapping
    public List<DeliveryResponse> all() {
        return service.findAll().stream().map(DeliveryResponse::from).toList();
    }

    @GetMapping("/{id}")
    public DeliveryResponse one(@PathVariable Long id) {
        return DeliveryResponse.from(service.require(id));
    }

    @PostMapping
    public ResponseEntity<DeliveryResponse> create(@Valid @RequestBody DeliveryRequest request) {
        Delivery delivery = service.create(request.customerId(), request.quantity(), request.notes());
        return ResponseEntity.created(URI.create("/api/deliveries/" + delivery.getId()))
                .body(DeliveryResponse.from(delivery));
    }

    @PutMapping("/{id}")
    public DeliveryResponse update(@PathVariable Long id,
                                   @Valid @RequestBody DeliveryRequest request) {
        return DeliveryResponse.from(service.update(
                id, request.customerId(), request.quantity(), request.notes()));
    }

    @DeleteMapping("/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public void delete(@PathVariable Long id) { service.delete(id); }
}
