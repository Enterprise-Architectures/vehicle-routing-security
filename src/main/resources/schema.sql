-- Lab 4: PostgreSQL DDL. Idempotent startup, no data is dropped.
CREATE TABLE IF NOT EXISTS depots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  coordinates VARCHAR(64) NOT NULL,
  CONSTRAINT ck_depots_name CHECK (length(btrim(name)) > 0),
  CONSTRAINT ck_depots_coordinates CHECK (length(btrim(coordinates)) > 0)
);

CREATE TABLE IF NOT EXISTS drivers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  phone VARCHAR(32) NOT NULL,
  CONSTRAINT ck_drivers_name CHECK (length(btrim(name)) > 0),
  CONSTRAINT ck_drivers_email CHECK (length(btrim(email)) > 0),
  CONSTRAINT ck_drivers_phone CHECK (length(btrim(phone)) > 0)
);

CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  phone VARCHAR(32) NOT NULL,
  address VARCHAR(255) NOT NULL,
  coordinates VARCHAR(64) NOT NULL,
  CONSTRAINT ck_customers_name CHECK (length(btrim(name)) > 0),
  CONSTRAINT ck_customers_email CHECK (length(btrim(email)) > 0),
  CONSTRAINT ck_customers_phone CHECK (length(btrim(phone)) > 0),
  CONSTRAINT ck_customers_address CHECK (length(btrim(address)) > 0),
  CONSTRAINT ck_customers_coordinates CHECK (length(btrim(coordinates)) > 0)
);

CREATE TABLE IF NOT EXISTS vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  capacity INTEGER NOT NULL,
  depot_id BIGINT NOT NULL REFERENCES depots(id) ON DELETE RESTRICT,
  available BOOLEAN NOT NULL DEFAULT TRUE,
  driver_id BIGINT UNIQUE REFERENCES drivers(id) ON DELETE SET NULL,
  CONSTRAINT ck_vehicles_name CHECK (length(btrim(name)) > 0),
  CONSTRAINT ck_vehicles_capacity CHECK (capacity > 0)
);

CREATE TABLE IF NOT EXISTS deliveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
  quantity INTEGER NOT NULL,
  notes VARCHAR(1000),
  "timestamp" TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_deliveries_quantity CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS idx_vehicles_depot ON vehicles(depot_id);
CREATE INDEX IF NOT EXISTS idx_deliveries_customer ON deliveries(customer_id);
CREATE INDEX IF NOT EXISTS idx_deliveries_timestamp ON deliveries("timestamp");

-- LAB 5 HOMEWORK 1: Scenario membership is many-to-many, materialized by two join tables.
CREATE TABLE IF NOT EXISTS scenarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  CONSTRAINT ck_scenarios_name CHECK (length(btrim(name)) > 0)
);
CREATE TABLE IF NOT EXISTS scenario_vehicles (
  scenario_id BIGINT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE RESTRICT,
  PRIMARY KEY (scenario_id, vehicle_id)
);
CREATE TABLE IF NOT EXISTS scenario_deliveries (
  scenario_id BIGINT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  delivery_id BIGINT NOT NULL REFERENCES deliveries(id) ON DELETE RESTRICT,
  PRIMARY KEY (scenario_id, delivery_id)
);
CREATE INDEX IF NOT EXISTS idx_scenario_vehicles_vehicle ON scenario_vehicles(vehicle_id);
CREATE INDEX IF NOT EXISTS idx_scenario_deliveries_delivery ON scenario_deliveries(delivery_id);

-- LAB 6: A common login account can be ADMIN, linked CUSTOMER, or linked DRIVER.
-- Passwords are BCrypt hashes; neither password nor hash is exposed by REST DTOs.
CREATE TABLE IF NOT EXISTS app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN', 'CUSTOMER', 'DRIVER')),
  customer_id BIGINT UNIQUE REFERENCES customers(id) ON DELETE RESTRICT,
  driver_id BIGINT UNIQUE REFERENCES drivers(id) ON DELETE RESTRICT,
  CONSTRAINT ck_app_users_profile CHECK (
      (role = 'ADMIN' AND customer_id IS NULL AND driver_id IS NULL)
   OR (role = 'CUSTOMER' AND customer_id IS NOT NULL AND driver_id IS NULL)
   OR (role = 'DRIVER' AND customer_id IS NULL AND driver_id IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS idx_app_users_role ON app_users(role);
